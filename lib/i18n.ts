export const dictionaries: Record<Locale, Dict> = { id, en };

/** The saved choice wins; otherwise a browser whose first language is Indonesian gets Indonesian. */
export function resolveLocale(saved: string | undefined, acceptLanguage: string | null): Locale {
  if (saved === "id" || saved === "en") return saved;
  return /^\s*id\b/i.test(acceptLanguage ?? "") ? "id" : "en";
}

let current: Dict = en;

/** The active dictionary for code outside React rendering (toasts in event handlers). */
export function getT(): Dict {
  return current;
}

/** Called by the provider so `getT()` follows the person's choice. */
export function setActiveDict(dict: Dict): void {
  current = dict;
}
